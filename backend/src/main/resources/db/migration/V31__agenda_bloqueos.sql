-- Días y horas sin servicio: el encargado bloquea un rango para todo el negocio
-- (empleado_id vacío) o solo para una persona (vacaciones, permiso).
CREATE TABLE agenda_bloqueo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT       NOT NULL REFERENCES negocio (id),
    empleado_id   BIGINT       REFERENCES usuario (id),
    inicio        TIMESTAMP    NOT NULL,
    fin           TIMESTAMP    NOT NULL,
    motivo        VARCHAR(80),
    creado_por_id BIGINT       REFERENCES usuario (id),
    creado        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_agenda_bloqueo_rango CHECK (fin > inicio)
);

CREATE INDEX ix_agenda_bloqueo_negocio ON agenda_bloqueo (negocio_id, fin);
