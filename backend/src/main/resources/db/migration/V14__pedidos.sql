-- Pedidos en tiempo real: se registran los encargos hechos en el sitio, se avisan con
-- notificaciones push y los atienden encargados y repartidores desde el panel.

ALTER TABLE usuario DROP CONSTRAINT ck_usuario_rol;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_rol CHECK (rol IN ('DUENO', 'ENCARGADO', 'REPARTIDOR'));

CREATE TABLE pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id       BIGINT         NOT NULL REFERENCES negocio (id),
    folio            VARCHAR(20),
    tipo             VARCHAR(60)    NOT NULL,
    modo             VARCHAR(10)    NOT NULL,
    cliente_nombre   VARCHAR(80)    NOT NULL,
    cliente_telefono VARCHAR(15)    NOT NULL,
    entregar         VARCHAR(300)   NOT NULL,
    zona             VARCHAR(80),
    total_estimado   DECIMAL(10, 2),
    -- El mismo texto que el cliente manda por WhatsApp.
    mensaje          VARCHAR(4000)  NOT NULL,
    estado           VARCHAR(12)    DEFAULT 'NUEVO' NOT NULL,
    repartidor_id    BIGINT REFERENCES usuario (id),
    creado           TIMESTAMP      NOT NULL,
    actualizado      TIMESTAMP      NOT NULL,
    CONSTRAINT uq_pedido_folio UNIQUE (folio),
    CONSTRAINT ck_pedido_estado CHECK (estado IN ('NUEVO', 'ACEPTADO', 'EN_CAMINO', 'ENTREGADO', 'CANCELADO'))
);
CREATE INDEX ix_pedido_negocio_estado ON pedido (negocio_id, estado);

-- Celulares que aceptaron recibir notificaciones (una fila por navegador).
CREATE TABLE push_suscripcion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT        NOT NULL REFERENCES usuario (id),
    endpoint   VARCHAR(1000) NOT NULL,
    p256dh     VARCHAR(200)  NOT NULL,
    auth       VARCHAR(100)  NOT NULL,
    creado     TIMESTAMP     NOT NULL,
    CONSTRAINT uq_push_endpoint UNIQUE (endpoint)
);
CREATE INDEX ix_push_usuario ON push_suscripcion (usuario_id);

-- Ajustes internos (p. ej. las llaves VAPID de las notificaciones, generadas solas).
CREATE TABLE ajuste (
    clave VARCHAR(60)   PRIMARY KEY,
    valor VARCHAR(2000) NOT NULL
);
