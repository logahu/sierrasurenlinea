-- Encarguitos: la "lista del mandado" (tarjetas de ¿Qué necesitas?) pasa del código a la base,
-- para editarla desde el panel. Se agrega "Viaje en moto" (con el sitio aliado), oculto hasta
-- que el dueño revise sus tarifas y lo active.
CREATE TABLE tipo_encargo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id          BIGINT       NOT NULL REFERENCES negocio (id),
    titulo              VARCHAR(60)  NOT NULL,
    ayuda               VARCHAR(80),
    ejemplo             VARCHAR(200),
    -- Etiqueta del campo "dónde empezamos": "Dónde comprar", "Dónde te recogemos"...
    etiqueta_recoger    VARCHAR(60)  NOT NULL,
    recoger_obligatorio BOOLEAN      DEFAULT FALSE NOT NULL,
    -- Si implica pagar algo además del envío (compras, recibos): pregunta quién paga.
    maneja_dinero       BOOLEAN      DEFAULT FALSE NOT NULL,
    -- MANDADO (llevar cosas) o VIAJE (llevar a una persona).
    modo                VARCHAR(10)  DEFAULT 'MANDADO' NOT NULL,
    icono               VARCHAR(20)  DEFAULT 'estrella' NOT NULL,
    -- Si está activo, el cliente no puede pedir "lo antes posible", solo con hora.
    solo_programado     BOOLEAN      DEFAULT FALSE NOT NULL,
    orden               INTEGER      DEFAULT 0 NOT NULL,
    visible             BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT ck_tipo_encargo_modo CHECK (modo IN ('MANDADO', 'VIAJE'))
);

CREATE INDEX ix_tipo_encargo_negocio ON tipo_encargo (negocio_id);

