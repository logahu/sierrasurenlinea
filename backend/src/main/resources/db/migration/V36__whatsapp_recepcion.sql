-- Recepcionista IA (fase 2): el WhatsApp de cada negocio conectado a la API de Meta (Cloud API).

-- Con qué número de la API contesta cada negocio (el "Phone number ID" de Meta) y si el bot está prendido.
-- Un webhook para todos: el negocio se reconoce por el phone_number_id que viene en cada mensaje.
ALTER TABLE negocio ADD COLUMN wa_phone_number_id VARCHAR(30);
ALTER TABLE negocio ADD CONSTRAINT uk_negocio_wa_phone_number UNIQUE (wa_phone_number_id);
ALTER TABLE negocio ADD COLUMN bot_activo BOOLEAN DEFAULT FALSE NOT NULL;

-- Una conversación por negocio y cliente de WhatsApp.
-- wa_id: como lo manda Meta (México: 521 + 10 dígitos); telefono: los 10 dígitos (para ligar con cliente).
-- user_id: identificador de usuario de Meta (llegará sin teléfono cuando se usen nombres de usuario).
-- humano_hasta: mientras esté en el futuro el bot no contesta (alguien del negocio tomó la conversación).
-- ultimo_entrante: para la ventana de 24 h en que se puede contestar sin plantilla.
CREATE TABLE wa_conversacion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id       BIGINT       NOT NULL REFERENCES negocio (id),
    wa_id            VARCHAR(20)  NOT NULL,
    telefono         VARCHAR(10),
    user_id          VARCHAR(60),
    nombre_perfil    VARCHAR(120),
    humano_hasta     TIMESTAMP,
    ultimo_entrante  TIMESTAMP,
    creado           TIMESTAMP    NOT NULL,
    actualizado      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_wa_conversacion UNIQUE (negocio_id, wa_id)
);

-- Mensajes de la conversación. wamid: id de Meta; único para no procesar dos veces un reintento.
-- direccion: ENTRANTE (cliente), SALIENTE (bot) o NEGOCIO (escrito desde la app WhatsApp Business).
-- estado de los salientes: ENVIADO, ENTREGADO, LEIDO, FALLIDO (llega por los webhooks de estado).
CREATE TABLE wa_mensaje (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id  BIGINT        NOT NULL REFERENCES wa_conversacion (id),
    wamid            VARCHAR(200)  UNIQUE,
    direccion        VARCHAR(10)   NOT NULL,
    tipo             VARCHAR(20)   NOT NULL,
    texto            VARCHAR(4096),
    estado           VARCHAR(10),
    error            VARCHAR(300),
    creado           TIMESTAMP     NOT NULL,
    CONSTRAINT ck_wa_mensaje_direccion CHECK (direccion IN ('ENTRANTE', 'SALIENTE', 'NEGOCIO'))
);
CREATE INDEX ix_wa_mensaje_conversacion ON wa_mensaje (conversacion_id, creado);
