-- Categorías. campos_atributos: JSON con los campos propios de la categoría
-- [{nombre, etiqueta, tipo: TEXTO|NUMERO|OPCION|SI_NO, requerido, opciones?, unidad?}].
CREATE TABLE tianguis_categoria (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(60)   NOT NULL,
    slug             VARCHAR(60)   NOT NULL UNIQUE,
    icono            VARCHAR(30),
    orden            INTEGER       DEFAULT 0 NOT NULL,
    activa           BOOLEAN       DEFAULT TRUE NOT NULL,
    campos_atributos VARCHAR(4000) DEFAULT '[]' NOT NULL
);

-- Vendedores: se identifican por su WhatsApp (12 dígitos, con lada 52). Sin cuenta.
CREATE TABLE tianguis_vendedor (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    whatsapp        VARCHAR(12)  NOT NULL UNIQUE,
    verificado      BOOLEAN      DEFAULT FALSE NOT NULL,
    bloqueado       BOOLEAN      DEFAULT FALSE NOT NULL,
    fecha_registro  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    notas_internas  VARCHAR(1000)
);

CREATE TABLE tianguis_anuncio (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             VARCHAR(80)    NOT NULL,
    descripcion        VARCHAR(2000)  NOT NULL,
    precio             NUMERIC(12, 2) NOT NULL,
    negociable         BOOLEAN        DEFAULT FALSE NOT NULL,
    condicion          VARCHAR(15)    NOT NULL,
    estado             VARCHAR(10)    NOT NULL,
    modalidad          VARCHAR(12)    DEFAULT 'CLASIFICADO' NOT NULL,
    categoria_id       BIGINT         NOT NULL REFERENCES tianguis_categoria (id),
    vendedor_id        BIGINT         NOT NULL REFERENCES tianguis_vendedor (id),
    -- URLs públicas de las fotos en orden (JSON); la primera es la portada.
    fotos              VARCHAR(4000)  NOT NULL,
    atributos          VARCHAR(4000)  DEFAULT '{}' NOT NULL,
    ubicacion          VARCHAR(80)    NOT NULL,
    destacado          BOOLEAN        DEFAULT FALSE NOT NULL,
    motivo_rechazo     VARCHAR(300),
    -- Quién lo pausó: VENDEDOR, ADMIN, REPORTES o BLOQUEO (solo el vendedor reanuda lo que él pausó).
    pausado_por        VARCHAR(10),
    renovaciones       INTEGER        DEFAULT 0 NOT NULL,
    -- SHA-256 del enlace privado de gestión (el token nunca se guarda).
    token_hash         VARCHAR(64)    UNIQUE,
    -- Título, descripción y atributos sin acentos ni mayúsculas, para buscar igual en cualquier base.
    busqueda           VARCHAR(3000)  NOT NULL,
    ip_origen          VARCHAR(60),
    fecha_creacion     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado        TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_publicacion  TIMESTAMP,
    fecha_vencimiento  TIMESTAMP,
    fecha_vendido      TIMESTAMP,
    vistas             INTEGER        DEFAULT 0 NOT NULL,
    CONSTRAINT ck_tianguis_condicion CHECK (condicion IN ('NUEVO_SIN_USO', 'SEMINUEVO', 'USADO', 'REPARADO')),
    CONSTRAINT ck_tianguis_estado CHECK (estado IN ('PENDIENTE', 'PUBLICADO', 'VENDIDO', 'VENCIDO', 'RECHAZADO', 'PAUSADO')),
    CONSTRAINT ck_tianguis_modalidad CHECK (modalidad IN ('CLASIFICADO', 'CONSIGNACION', 'PROPIO')),
    CONSTRAINT ck_tianguis_precio CHECK (precio >= 0)
);

CREATE INDEX ix_tianguis_anuncio_estado_cat ON tianguis_anuncio (estado, categoria_id, fecha_publicacion);
CREATE INDEX ix_tianguis_anuncio_estado_precio ON tianguis_anuncio (estado, precio);
CREATE INDEX ix_tianguis_anuncio_vendedor ON tianguis_anuncio (vendedor_id, fecha_creacion);

CREATE TABLE tianguis_reporte (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id  BIGINT        NOT NULL REFERENCES tianguis_anuncio (id),
    motivo      VARCHAR(20)   NOT NULL,
    comentario  VARCHAR(500),
    fecha       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atendido    BOOLEAN       DEFAULT FALSE NOT NULL,
    ip          VARCHAR(60),
    CONSTRAINT ck_tianguis_reporte_motivo CHECK (motivo IN ('FRAUDE', 'PROHIBIDO', 'VENDIDO', 'FALSO', 'OTRO'))
);

CREATE INDEX ix_tianguis_reporte_anuncio ON tianguis_reporte (anuncio_id, atendido);

