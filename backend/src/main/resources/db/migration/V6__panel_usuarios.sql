-- Panel de administración (fase 1): usuarios con rol y negocios que se pueden ocultar.

-- Un negocio oculto no aparece en la portada ni en el menú, y su página da 404.
ALTER TABLE negocio ADD COLUMN visible BOOLEAN DEFAULT TRUE NOT NULL;

-- Personas que entran al panel. DUENO ve todo; ENCARGADO solo su negocio.
-- La contraseña se guarda como hash bcrypt, nunca en texto.
CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo             VARCHAR(120) NOT NULL,
    nombre             VARCHAR(80)  NOT NULL,
    contrasena_hash    VARCHAR(100) NOT NULL,
    rol                VARCHAR(10)  NOT NULL,
    negocio_id         BIGINT REFERENCES negocio (id),
    activo             BOOLEAN      DEFAULT TRUE NOT NULL,
    intentos_fallidos  INTEGER      DEFAULT 0 NOT NULL,
    bloqueado_hasta    TIMESTAMP,
    creado             TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('DUENO', 'ENCARGADO')),
    -- El encargado siempre tiene negocio; el dueño no lo necesita.
    CONSTRAINT ck_usuario_negocio CHECK (rol = 'DUENO' OR negocio_id IS NOT NULL)
);

CREATE INDEX ix_usuario_negocio ON usuario (negocio_id);
