-- Colonias, barrios y comunidades de Miahuatlán para elegir al hacer un pedido.
-- Carga inicial: Catálogo Nacional de Códigos Postales (Correos de México).
-- zona = nombre de la tarifa de Encarguitos que le corresponde (p. ej. "Centro"); null = el cliente la elige.
-- estado: ACTIVA (se ofrece) o SOLICITADA (un cliente la escribió en «Otra» y espera revisión).
CREATE TABLE colonia (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    tipo          VARCHAR(20)  NOT NULL DEFAULT 'Colonia',
    codigo_postal VARCHAR(5),
    zona          VARCHAR(80),
    estado        VARCHAR(12)  NOT NULL DEFAULT 'ACTIVA',
    origen        VARCHAR(10)  NOT NULL DEFAULT 'SEPOMEX',
    solicitudes   INT          NOT NULL DEFAULT 0,
    creada        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_colonia_estado ON colonia (estado);

ALTER TABLE pedido ADD COLUMN colonia VARCHAR(100);
-- El cliente eligió «Otra» y la escribió él.
ALTER TABLE pedido ADD COLUMN colonia_otra BOOLEAN DEFAULT FALSE NOT NULL;

