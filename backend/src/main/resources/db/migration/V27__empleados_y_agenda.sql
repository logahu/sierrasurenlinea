-- Empleados (estilistas, barberos…) que da de alta el encargado, y agenda de citas con horarios libres.
ALTER TABLE usuario DROP CONSTRAINT ck_usuario_rol;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_rol CHECK (rol IN ('DUENO', 'ENCARGADO', 'REPARTIDOR', 'EMPLEADO'));
-- «Cortes, barba»: se muestra al cliente al elegir con quién.
ALTER TABLE usuario ADD COLUMN especialidades VARCHAR(200);
-- El encargado también puede atender citas (los empleados siempre atienden).
ALTER TABLE usuario ADD COLUMN atiende_citas BOOLEAN DEFAULT FALSE NOT NULL;

-- Agenda: horario por día de la semana en JSON {"1":["10:00","19:00"], ... "7":null} (1 = lunes)
-- y minutos que dura cada servicio.
ALTER TABLE negocio ADD COLUMN agenda_activa BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE negocio ADD COLUMN horario_citas VARCHAR(500);
ALTER TABLE negocio ADD COLUMN minutos_cita INTEGER DEFAULT 60 NOT NULL;

-- La cita del pedido: quién atiende y de qué hora a qué hora (hora de Miahuatlán).
ALTER TABLE pedido ADD COLUMN empleado_id BIGINT REFERENCES usuario (id);
ALTER TABLE pedido ADD COLUMN cita_inicio TIMESTAMP;
ALTER TABLE pedido ADD COLUMN cita_fin TIMESTAMP;
CREATE INDEX ix_pedido_cita ON pedido (negocio_id, cita_inicio);

-- Cada bloque de tiempo apartado. La llave única impide que dos clientes aparten la misma hora
-- con la misma persona aunque pidan al mismo tiempo. Al cancelar la cita se borran sus bloques.
CREATE TABLE cita_bloque (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id   BIGINT    NOT NULL REFERENCES pedido (id),
    empleado_id BIGINT    NOT NULL REFERENCES usuario (id),
    inicio      TIMESTAMP NOT NULL,
    CONSTRAINT uk_cita_bloque UNIQUE (empleado_id, inicio)
);

-- Estudio Melgarejo: lunes a sábado de 10:00 a 19:00, domingo cerrado, 1 hora por servicio.
