-- Cuentas de clientes: para hacer un pedido hay que registrarse (teléfono y contraseña).
-- Solo bajas lógicas: un cliente desactivado no puede entrar, pero su historial se conserva.
CREATE TABLE cliente (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(80)  NOT NULL,
    -- 10 dígitos, sin lada de país: es el usuario para entrar.
    telefono            VARCHAR(10)  NOT NULL,
    correo              VARCHAR(120),
    -- Dirección de entrega habitual (se propone en cada pedido).
    direccion           VARCHAR(300),
    contrasena_hash     VARCHAR(100) NOT NULL,
    activo              BOOLEAN      DEFAULT TRUE NOT NULL,
    intentos_fallidos   INTEGER      DEFAULT 0 NOT NULL,
    bloqueado_hasta     TIMESTAMP,
    -- Cuándo aceptó el aviso de privacidad y qué versión.
    privacidad_aceptada TIMESTAMP    NOT NULL,
    privacidad_version  VARCHAR(20)  NOT NULL,
    creado              TIMESTAMP    NOT NULL,
    ultimo_acceso       TIMESTAMP,
    CONSTRAINT uq_cliente_telefono UNIQUE (telefono)
);

ALTER TABLE pedido ADD COLUMN cliente_id BIGINT REFERENCES cliente (id);
CREATE INDEX ix_pedido_cliente ON pedido (cliente_id);
