-- Banners de publicidad de la portada. El visitante puede ocultarlos; siempre dicen «Publicidad».
CREATE TABLE anuncio (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      VARCHAR(80)  NOT NULL,
    texto       VARCHAR(200),
    imagen_url  VARCHAR(500),
    -- Ruta del sitio (/turamohoy) o URL https://; vacío = el banner no lleva a ningún lado.
    enlace      VARCHAR(300),
    negocio_id  BIGINT REFERENCES negocio (id),
    color_fondo VARCHAR(7),
    -- PORTADA_ARRIBA (bajo el encabezado) o ENTRE_CALLES (después de la segunda calle).
    posicion    VARCHAR(20)  NOT NULL,
    -- Fechas de Miahuatlán, inclusivas; vacías = sin límite.
    inicio      DATE,
    fin         DATE,
    activo      BOOLEAN      DEFAULT TRUE NOT NULL,
    orden       INTEGER      DEFAULT 0 NOT NULL,
    creado      TIMESTAMP,
    CONSTRAINT ck_anuncio_posicion CHECK (posicion IN ('PORTADA_ARRIBA', 'ENTRE_CALLES'))
);
CREATE INDEX ix_anuncio_posicion ON anuncio (posicion, activo);
