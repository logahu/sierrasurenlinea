-- Portada «calles por giro»: cada negocio pertenece a un giro (una calle de la portada).
-- Es tabla y no enum para poder crear giros sin hacer deploy.
CREATE TABLE giro (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug   VARCHAR(40)  NOT NULL,
    nombre VARCHAR(60)  NOT NULL,
    -- Nombre corto del dibujo (flor, belleza, fiesta, bebida, comida, auto, moto); el sitio lo pinta en SVG.
    icono  VARCHAR(30),
    orden  INTEGER      DEFAULT 0 NOT NULL,
    CONSTRAINT uq_giro_slug UNIQUE (slug)
);

