-- Historial (bitácora): quién hizo qué y cuándo. Nunca se borra.
CREATE TABLE bitacora (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuando       TIMESTAMP     NOT NULL,
    -- USUARIO (panel), CLIENTE (sitio) o SISTEMA
    actor_tipo   VARCHAR(10)   NOT NULL,
    actor_id     BIGINT,
    actor_nombre VARCHAR(80)   NOT NULL,
    negocio_id   BIGINT REFERENCES negocio (id),
    -- NEGOCIO, PRODUCTO, CATEGORIA, USUARIO, CLIENTE, PEDIDO, FOTO, ENCARGO, COMIDA
    entidad      VARCHAR(20)   NOT NULL,
    entidad_id   BIGINT,
    accion       VARCHAR(200)  NOT NULL,
    detalle      VARCHAR(1000)
);
CREATE INDEX ix_bitacora_cuando ON bitacora (cuando);
CREATE INDEX ix_bitacora_entidad ON bitacora (entidad, entidad_id);
CREATE INDEX ix_bitacora_negocio ON bitacora (negocio_id);

-- Fotos subidas a R2. Al borrar una foto se elimina el archivo para liberar espacio,
-- pero el registro se conserva (con la fecha en que se borró).
CREATE TABLE foto (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id BIGINT        NOT NULL REFERENCES negocio (id),
    clave      VARCHAR(300)  NOT NULL,
    url        VARCHAR(500)  NOT NULL,
    tipo       VARCHAR(30)   NOT NULL,
    bytes      BIGINT        NOT NULL,
    subida     TIMESTAMP     NOT NULL,
    subida_por BIGINT REFERENCES usuario (id),
    borrada    TIMESTAMP,
    borrada_por BIGINT REFERENCES usuario (id),
    CONSTRAINT uq_foto_clave UNIQUE (clave)
);
CREATE INDEX ix_foto_negocio ON foto (negocio_id);

-- Avisos push a los clientes cuando cambia el estado de su pedido.
CREATE TABLE push_cliente (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT        NOT NULL REFERENCES cliente (id),
    endpoint   VARCHAR(1000) NOT NULL,
    p256dh     VARCHAR(200)  NOT NULL,
    auth       VARCHAR(100)  NOT NULL,
    creado     TIMESTAMP     NOT NULL,
    CONSTRAINT uq_push_cliente_endpoint UNIQUE (endpoint)
);
CREATE INDEX ix_push_cliente ON push_cliente (cliente_id);
