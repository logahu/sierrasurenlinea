-- Pedidos homologados: todos los negocios reciben pedidos en línea con carrito.
-- Cada negocio indica cómo se piden sus productos:
--   COMPRA (florería, belleza, vinatería): entrega a domicilio o recoger en el negocio.
--   RENTA  (inflables): fecha del evento obligatoria, se lleva al lugar del evento.
--   CITA   (autos): el cliente pide una visita para ver el producto en persona.
-- Los negocios de servicio (Encarguitos) siguen con su propio formulario.
ALTER TABLE negocio ADD COLUMN modo_pedido VARCHAR(10);
UPDATE negocio SET modo_pedido = 'COMPRA' WHERE tipo = 'VENTA';
UPDATE negocio SET modo_pedido = 'RENTA' WHERE tipo = 'RENTA';
UPDATE negocio SET modo_pedido = 'CITA' WHERE slug = 'autos';

-- Datos de entrega comunes a todos los pedidos.
ALTER TABLE pedido ADD COLUMN entrega VARCHAR(10);
ALTER TABLE pedido ADD COLUMN cuando VARCHAR(120);
ALTER TABLE pedido ADD COLUMN notas VARCHAR(500);

-- Renglones del pedido. Se copian nombre y precio del momento, para que el historial
-- no cambie si después se edita o se da de baja el producto.
CREATE TABLE pedido_linea (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id),
    producto_id     BIGINT REFERENCES producto (id),
    nombre          VARCHAR(120)   NOT NULL,
    cantidad        INTEGER        NOT NULL,
    precio_unitario DECIMAL(10, 2) NOT NULL,
    unidad          VARCHAR(30),
    orden           INTEGER        NOT NULL,
    CONSTRAINT ck_pedido_linea_cantidad CHECK (cantidad > 0)
);
CREATE INDEX ix_pedido_linea_pedido ON pedido_linea (pedido_id);

-- Repartidores generales: sin negocio, entregan los pedidos a domicilio de todos.
ALTER TABLE usuario DROP CONSTRAINT ck_usuario_negocio;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_negocio CHECK (rol IN ('DUENO', 'REPARTIDOR') OR negocio_id IS NOT NULL);
