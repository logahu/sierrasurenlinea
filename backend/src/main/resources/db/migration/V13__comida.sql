-- Encarguitos: "Comida a domicilio". Un catálogo de lugares de comida (fondas, taquerías...)
-- con sus platillos; el cliente arma su pedido y Encarguitos lo compra y lo lleva.

ALTER TABLE tipo_encargo DROP CONSTRAINT ck_tipo_encargo_modo;
ALTER TABLE tipo_encargo ADD CONSTRAINT ck_tipo_encargo_modo CHECK (modo IN ('MANDADO', 'VIAJE', 'COMIDA'));

CREATE TABLE restaurante (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT        NOT NULL REFERENCES negocio (id),
    nombre      VARCHAR(80)   NOT NULL,
    descripcion VARCHAR(200),
    -- Texto libre: "Lun a Sáb 8:00 – 16:00".
    horario     VARCHAR(120),
    direccion   VARCHAR(200),
    imagen_url  VARCHAR(500),
    orden       INTEGER       DEFAULT 0 NOT NULL,
    visible     BOOLEAN       DEFAULT TRUE NOT NULL
);
CREATE INDEX ix_restaurante_negocio ON restaurante (negocio_id);

CREATE TABLE platillo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id BIGINT        NOT NULL REFERENCES restaurante (id),
    nombre         VARCHAR(100)  NOT NULL,
    descripcion    VARCHAR(300),
    precio         DECIMAL(10, 2) NOT NULL,
    imagen_url     VARCHAR(500),
    orden          INTEGER       DEFAULT 0 NOT NULL,
    disponible     BOOLEAN       DEFAULT TRUE NOT NULL
);
CREATE INDEX ix_platillo_restaurante ON platillo (restaurante_id);

